// 仅在专用测试扩展中执行；受控响应验证交互，真实服务另行检查。
async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  assert(page.url().startsWith('chrome-extension://'), '请使用测试扩展');
  const calls = [], errors = [];
  await page.unrouteAll({ behavior: 'ignoreErrors' });
  await page.addInitScript(() => {
    const spoken = [];
    const engine = new EventTarget();
    engine.getVoices = () => ['en-US', 'zh-CN', 'ja-JP'].map(lang => ({ name: `Test ${lang}`, lang, localService: true }));
    engine.cancel = () => {};
    engine.speak = utterance => { spoken.push({ text: utterance.text, language: utterance.voice.lang }); utterance.onstart?.(); utterance.onend?.(); };
    window.__workspaceSpoken = spoken;
    Object.defineProperty(window, 'speechSynthesis', { value: engine });
    Object.defineProperty(window, 'SpeechSynthesisUtterance', { value: class { constructor(text) { this.text = text; } } });
  });
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://edge.microsoft.com/**', async route => {
    const text = JSON.parse(route.request().postData())[0];
    const target = new URL(route.request().url()).searchParams.get('to');
    calls.push({ text, target });
    if (text === 'Please wait for this translation.') await page.waitForTimeout(1400);
    if (text === 'Please show the failure.') return route.fulfill({ status: 503 });
    const translation = text === '回溯' ? 'Looking back' : text === '東京' ? target === 'en' ? 'Tokyo' : '东京' : text === 'Please wait for this translation.' ? '请等待这次翻译。' : target === 'ja' ? '更新された設計を確認してください。' : '请查看更新后的设计。';
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify([{ detectedLanguage: { language: text === '回溯' ? 'zh' : text === '東京' ? 'ja' : 'en' }, translations: [{ text: translation }] }]) }).catch(() => {});
  });
  await page.route('https://cn.bing.com/**', async route => {
    await page.waitForTimeout(450);
    return route.fulfill({ status: 200, contentType: 'text/html', body: '<div class="qdef"><div id="headword">回溯</div><ul><li><span class="pos">v.</span><span class="def">recall</span></li></ul></div>' }).catch(() => {});
  });
  await page.evaluate(async () => { sessionStorage.clear(); await chrome.storage.local.clear(); });
  await page.reload();
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  const input = page.getByRole('textbox', { name: '输入要翻译的文本' });
  const output = page.getByRole('region', { name: '翻译结果', exact: true });
  const target = page.getByRole('combobox', { name: '译文语言', exact: true });
  await input.fill('回溯');
  await page.getByText('backtracking', { exact: true }).waitFor();
  assert(await page.locator('.alternative-text').first().textContent() === 'backtracking', '有语境的算法含义应先展示');
  assert(await page.locator('#result-text').isVisible() === false, '词语不再有独立的大号默认译文');
  await page.getByText('backtrack', { exact: true }).dblclick();
  await page.getByText('recall', { exact: true }).waitFor();
  assert(await page.evaluate(() => getSelection().toString()) === 'backtrack', '词典晚到应保留原生选区');
  const sizes = await page.locator('.alternative-text').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).fontSize));
  assert(new Set(sizes).size === 1, '全部译法使用同一文字层级');
  await page.getByRole('button', { name: '复制 backtrack', exact: true }).click();
  assert(await page.evaluate(() => navigator.clipboard.readText()) === 'backtrack', '单项复制仍可用');
  await page.getByRole('button', { name: '复制全部译法', exact: true }).click();
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('Looking back'), '服务译法必须保留');
  await input.fill('Please wait for this translation.');
  await page.getByText('上次结果（英语） · 更新中', { exact: true }).waitFor();
  assert(await output.isVisible() && (await output.textContent()).includes('backtrack'), '更新时保留旧词义');
  assert(await page.getByRole('button', { name: '复制 backtrack', exact: true }).isEnabled(), '等待期间允许明确复制上次结果');
  await page.getByRole('button', { name: '朗读 backtrack', exact: true }).click();
  assert(await page.evaluate(() => __workspaceSpoken.at(-1).language) === 'en-US', '目标已改为中文时，上次英文结果仍使用英文声音');
  await output.filter({ hasText: '请等待这次翻译。' }).waitFor();
  assert(await page.locator('#alternatives-panel').isVisible() === false, '新句段完成后一次替换词义列表');
  assert(await page.locator('#previous-result-status').isVisible() === false, '完成后移除旧结果标记');
  await input.fill('Please show the failure.');
  await page.getByText('上次结果（中文） · 更新失败，仍可阅读和复制', { exact: true }).waitFor();
  await page.getByRole('button', { name: '复制译文', exact: true }).click();
  assert(await page.evaluate(() => navigator.clipboard.readText()) === '请等待这次翻译。', '失败也不能抹掉之前结果');
  await input.fill('Please review the updated design.');
  await output.filter({ hasText: '请查看更新后的设计。' }).waitFor();
  await target.selectOption('ja');
  await output.filter({ hasText: '更新された設計を確認してください。' }).waitFor();
  const beforeReload = calls.length;
  await page.reload();
  await page.getByText('结果已恢复', { exact: true }).waitFor();
  assert(await input.inputValue() === 'Please review the updated design.', '刷新应恢复原文');
  assert(await target.inputValue() === 'ja', '刷新应恢复目标语言');
  assert(calls.length === beforeReload, '已有匹配结果恢复时不应重复消耗服务额度');
  await page.getByRole('button', { name: '清空', exact: true }).click();
  assert(await output.isVisible() === false, '清空应移除旧结果');
  await page.getByRole('button', { name: '撤销清空', exact: true }).click();
  await output.filter({ hasText: '更新された設計を確認してください。' }).waitFor();
  assert(calls.length === beforeReload, '撤销清空应直接恢复原结果');
  await target.selectOption('auto');
  await output.filter({ hasText: '请查看更新后的设计。' }).waitFor();
  const beforeComposition = calls.length;
  await input.evaluate(el => { el.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })); el.value = 'nihao'; el.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true })); });
  assert(await output.isVisible(), '输入法选字期间也保留结果');
  assert(calls.length === beforeComposition, '组合输入期间不发请求');
  await input.evaluate(el => { el.value = '回溯'; el.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })); el.dispatchEvent(new InputEvent('input', { bubbles: true })); });
  await page.getByText('backtrack', { exact: true }).waitFor();
  assert(calls.length === beforeComposition + 1, '输入法确认后同步且仅请求一次');
  await page.getByRole('button', { name: '清空', exact: true }).click();
  await target.selectOption('auto');
  await input.fill('東京');
  await output.filter({ hasText: '东京' }).waitFor();
  const beforeTokyoReload = calls.length;
  await page.reload();
  await page.getByText('结果已恢复', { exact: true }).waitFor();
  assert(await target.inputValue() === 'auto', '自动语言修正后仍保持自动选择');
  assert((await output.textContent()).includes('东京') && calls.length === beforeTokyoReload, '恢复按服务识别修正过的结果，不重新猜测');
  const reused = await page.evaluate(async () => {
    const { createTranslationTabOpener } = await import(chrome.runtime.getURL('tabs.js'));
    const open = createTranslationTabOpener(chrome, chrome.runtime.getURL('index.html'));
    const current = await chrome.tabs.getCurrent();
    const ids = await Promise.all([open(current), open(current), open(current)]);
    return { current: current.id, ids, contexts: (await chrome.runtime.getContexts({ contextTypes: ['TAB'] })).filter(context => context.documentUrl.split('#')[0] === chrome.runtime.getURL('index.html')).length, permissions: chrome.runtime.getManifest().permissions };
  });
  assert(reused.ids.every(id => id === reused.current) && reused.contexts === 1, '连续打开应激活已有页面');
  assert(JSON.stringify(reused.permissions) === '["storage","contextMenus"]', '网页翻译只增加必要的右键权限，不添加tabs权限');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 980 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px 横向溢出`);
  }
  await page.setViewportSize({ width: 1100, height: 900 });
  await page.screenshot({ path: 'output/playwright/workspace-0.5.0.png' });
  assert(errors.length === 0, errors.join('; '));
  return { status: 'passed', requests: calls.length, checks: ['词义同一层级和语境优先', '词典晚到保留选区', '单项及全部复制', '更新和失败保留结果', '旧结果按原语言朗读', '句段完整替换', '刷新恢复不重复请求', '目标语言恢复', '撤销清空', 'IME去重', '自动语言修正恢复', '真实扩展API复用标签页', 'storage和contextMenus权限，无tabs权限', '390px和320px布局'], responseMode: 'controlled-fixtures', speech: 'controlled-events' };
}
