// 在专用测试扩展中验证朗读控件；受控语音事件不代表实际听到了声音。
async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.unrouteAll({ behavior: 'ignoreErrors' });
  await page.route('https://edge.microsoft.com/**', route => {
    const input = JSON.parse(route.request().postData())[0];
    const text = input === '回溯' ? 'Retrospective' : '你好';
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify([{ translations: [{ text }] }]) });
  });
  await page.route('https://cn.bing.com/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<html>No additional entries</html>' }));
  await page.addInitScript(() => {
    const engine = new EventTarget();
    engine.voices = [{ name: 'Online English', lang: 'en-US', localService: false, default: true }, { name: 'System English', lang: 'en-US', localService: true }, { name: 'System Chinese', lang: 'zh-CN', localService: true }];
    engine.utterances = []; engine.canceled = 0;
    engine.getVoices = () => engine.voices;
    engine.speak = utterance => { engine.utterances.push(utterance); utterance.onstart(); };
    engine.cancel = () => { engine.canceled++; engine.utterances.at(-1)?.onerror?.({ error: 'canceled' }); };
    window.__speechTest = engine;
    Object.defineProperty(window, 'speechSynthesis', { value: engine });
    Object.defineProperty(window, 'SpeechSynthesisUtterance', { value: class { constructor(text) { this.text = text; } } });
  });
  await page.evaluate(() => chrome.storage.local.clear());
  await page.reload();
  const input = page.getByRole('textbox', { name: '输入要翻译的文本' });
  await input.fill('回溯');
  await page.getByRole('button', { name: '朗读 backtrack', exact: true }).waitFor();
  const beforePlayback = await page.locator('#copy-result').boundingBox();
  await page.getByRole('button', { name: '朗读例句 backtrack', exact: true }).click();
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).text) === 'backtrack to the previous choice', '例句小喇叭应朗读整句');
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).voice.lang) === 'en-US', '英文例句使用英文声音');
  await page.getByRole('button', { name: '朗读 backtrack', exact: true }).click();
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).text) === 'backtrack', '朗读候选应使用候选文本');
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).voice.name) === 'System English', '英文应使用本地声音');
  assert(await page.getByRole('button', { name: '停止朗读 backtrack', exact: true }).getAttribute('aria-pressed') === 'true', '正在朗读的候选显示停止');
  assert(await page.locator('#speech-status').isVisible() === false, '正常朗读不显示额外状态行');
  const duringPlayback = await page.locator('#copy-result').boundingBox();
  assert(beforePlayback.y === duringPlayback.y, '朗读不能顶起复制按钮');
  await page.getByRole('button', { name: '停止朗读 backtrack', exact: true }).click();
  await page.getByRole('button', { name: '朗读 backtrack', exact: true }).waitFor();
  assert(await page.locator('#speech-status').isVisible() === false, '主动停止不会显示错误');
  await page.getByRole('button', { name: '朗读译文', exact: true }).click();
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).text) === 'Retrospective', '主译文朗读保持独立');
  assert(await page.locator('#speech-status').isVisible() === false, '主译文朗读也不显示额外状态行');
  assert((await page.locator('#copy-result').boundingBox()).y === beforePlayback.y, '主译文朗读按钮位置保持不变');
  await page.screenshot({ path: 'output/playwright/speech-controls-stable-0.2.1.png', fullPage: true });
  await input.fill('Hello');
  await page.getByRole('region', { name: '翻译结果', exact: true }).filter({ hasText: '你好' }).waitFor();
  assert(await page.getByRole('button', { name: '停止朗读', exact: true }).count() === 0, '新输入会停止旧朗读');
  await page.getByRole('button', { name: '朗读译文', exact: true }).click();
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).voice.lang) === 'zh-CN', '中文译文应匹配中文声音');
  await input.fill('backtrack');
  await page.getByRole('button', { name: '朗读例句 回溯', exact: true }).click();
  assert(await page.evaluate(() => __speechTest.utterances.at(-1).voice.lang) === 'en-US', '英译中的英文例句不能用中文声音朗读');
  await page.getByRole('button', { name: '朗读译文', exact: true }).click();
  await page.evaluate(() => __speechTest.utterances.at(-1).onerror({ error: 'not-allowed' }));
  await page.getByText('浏览器未允许朗读，请重新点击朗读按钮。', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '复制译文', exact: true }).isEnabled(), '朗读失败不影响复制');
  await page.evaluate(() => { __speechTest.voices = __speechTest.voices.filter(voice => !voice.localService); });
  await page.getByRole('button', { name: '朗读译文', exact: true }).click();
  await page.getByText('未找到系统中文声音，请在系统设置中安装对应语音后重试。', { exact: true }).waitFor();
  await page.evaluate(() => { __speechTest.voices = []; });
  await page.getByRole('button', { name: '朗读译文', exact: true }).click();
  await page.getByRole('button', { name: '停止朗读', exact: true }).waitFor();
  assert(await page.locator('#speech-status').isVisible() === false, '准备声音时也不增加状态行');
  await page.getByRole('button', { name: '清空', exact: true }).click();
  const before = await page.evaluate(() => __speechTest.utterances.length);
  await page.evaluate(() => { __speechTest.voices = [{ name: 'System Chinese', lang: 'zh-CN', localService: true }]; __speechTest.dispatchEvent(new Event('voiceschanged')); });
  assert(await page.evaluate(() => __speechTest.utterances.length) === before, '清空后声音加载不能播放旧译文');
  assert(await page.getByRole('button', { name: '朗读译文', exact: true }).isDisabled(), '清空后禁用朗读');
  return { status: 'passed', checks: ['例句小喇叭', '英文例句独立语音方向', '正常朗读无状态行', '朗读按钮位置稳定', '候选独立朗读', '本地中英声音', '停止按钮', '新输入取消', '语音错误反馈', '复制不受影响', '异步声音取消'], speech: 'controlled-events' };
}
