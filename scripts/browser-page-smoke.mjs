async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const context = page.context();
  const worker = context.serviceWorkers()[0];
  assert(worker, '未加载测试扩展后台');
  await worker.evaluate(async () => {
    await chrome.storage.local.clear();
    await chrome.storage.local.set({ 'translation-settings-v1': { provider: 'microsoft', providers: {}, page: { target: 'zh', selection: true, floating: true } } });
  });
  const calls = [];
  let blocked = null, fail = false;
  await context.route('https://edge.microsoft.com/translate/translatetext?*', async route => {
    const texts = JSON.parse(route.request().postData());
    const target = new URL(route.request().url()).searchParams.get('to');
    calls.push({ texts, target });
    if (blocked) await blocked;
    if (fail) { await route.fulfill({ status: 429, body: '{}' }); return; }
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify(texts.map(text => ({ detectedLanguage: { language: /[\u4e00-\u9fff]/u.test(text) && text === '回溯' || text.startsWith('这是') ? 'zh-Hans' : 'en' }, translations: [{ text: text === '回溯' ? 'Retrospective' : text.startsWith('这是') ? text : `中文译文：${text}`, to: target }] }))) });
  });
  await context.route('https://cn.bing.com/dict/search?*', route => route.fulfill({ contentType: 'text/html', body: '<div id="headword">回溯</div><div class="qdef"><ul><li><span class="pos">v.</span><span class="def">backtrack; trace back</span></li></ul></div>' }));
  await page.reload();
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).waitFor();
  const original = await page.locator('main').innerHTML();
  assert(calls.length === 0, '没有主动启用前不发送页面文本');
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).evaluate(el => el.click());
  await page.waitForTimeout(100);
  assert(calls.length === 0, '网页合成点击不能主动启动翻译');
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).click();
  await page.locator('#first [data-ct-owned="translation"]').waitFor();
  assert((await page.locator('#first [aria-label="译文"]').textContent()).startsWith('中文译文：'), '原文下面显示译文');
  assert(await page.locator('#article-link strong').textContent() === 'working link', '格式和链接保持');
  await page.locator('#inline-code [data-ct-owned="translation"]').waitFor();
  assert(calls.flatMap(call => call.texts).some(text => text.includes('Array.map()')), '段落保留内联代码标识符');
  assert(await page.locator('#inline-code code').textContent() === 'Array.map()', '原内联代码保持');
  assert(await page.locator('#code [data-ct-owned]').count() === 0 && await page.locator('form [data-ct-owned]').count() === 0, '代码及表单不翻译');
  assert(await page.locator('nav [data-ct-owned]').count() === 0 && await page.locator('aside [data-ct-owned]').count() === 0, '正文模式排除导航和侧栏');
  assert(await page.locator('#same [data-ct-owned]').count() === 0, '已有目标语言不重复插入');
  assert(!calls.flatMap(call => call.texts).some(text => text.includes('private') || text.includes('secret') || text.includes('code unchanged')), '私有和代码文本不发送');
  assert(!calls.flatMap(call => call.texts).some(text => text.startsWith('The final')), '屏幕外远段落尚未发送');
  await page.locator('#dynamic').evaluate(el => { const p = document.createElement('p'); p.id = 'added'; p.textContent = 'A dynamically added paragraph is translated too.'; el.append(p); });
  await page.locator('#added [data-ct-owned="translation"]').waitFor();
  await page.locator('#first').evaluate(el => { el.firstChild.textContent = 'Changed original paragraph is translated again.'; });
  await page.locator('#first [aria-label="译文"]').filter({ hasText: 'Changed original' }).waitFor();
  await page.getByRole('button', { name: '显示原文', exact: true }).click();
  assert(await page.locator('main [data-ct-owned]').count() === 0, '关闭移除全部译文');
  await page.locator('#first').evaluate(el => { el.firstChild.textContent = 'A good translation keeps the original text visible. You can compare both languages as you read.'; });
  await page.locator('#dynamic').evaluate(el => el.replaceChildren());
  assert(await page.locator('main').innerHTML() === original, '源 DOM 完全恢复');
  const beforeCache = calls.length;
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).click();
  await page.locator('#first [data-ct-owned="translation"]').waitFor();
  assert(calls.length === beforeCache, '再次启用复用当前页内存缓存');
  await page.locator('#article-link').click();
  await page.locator('#lazy [data-ct-owned="translation"]').waitFor();
  assert(await page.locator('body').getAttribute('data-link-clicked') === 'yes', '原有链接点击事件正常');
  assert(calls.flatMap(call => call.texts).some(text => text.startsWith('The final')), '滚动后按需翻译');
  await page.getByRole('button', { name: '显示原文', exact: true }).click();
  await page.evaluate(() => scrollTo(0, 0));
  const selectTerm = async () => {
    await page.locator('#term').evaluate(el => {
      el.tabIndex = -1; el.focus();
      const range = document.createRange(), node = el.firstChild, start = node.textContent.indexOf('回溯');
      range.setStart(node, start); range.setEnd(node, start + 2); const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range);
    });
    await page.keyboard.press('Shift');
    await page.getByRole('button', { name: '翻译选中文字', exact: true }).waitFor();
  };
  const beforeSelect = calls.length;
  await selectTerm();
  assert(calls.length === beforeSelect, '划词只显示按钮，未点击时不发请求');
  await page.getByRole('button', { name: '翻译选中文字', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '划词翻译' });
  await panel.getByText('backtracking', { exact: true }).waitFor();
  await panel.getByText('backtrack', { exact: true }).waitFor();
  assert(calls.at(-1).target === 'en', '中文划词自动译英文');
  assert(await panel.getByRole('button', { name: '朗读例句', exact: true }).count() > 0, '例句有小喇叭');
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await panel.getByRole('button', { name: '复制 backtrack', exact: true }).click();
  assert(await page.evaluate(() => navigator.clipboard.readText()) === 'backtrack', '划词可复制');
  await page.screenshot({ path: 'output/playwright/page-selection-0.6.0.png' });
  await page.keyboard.press('Escape');
  assert(!await panel.isVisible(), 'Escape关闭浮层');
  const tabId = await worker.evaluate(async () => (await chrome.tabs.query({ url: 'http://127.0.0.1:4174/*' }))[0].id);
  await worker.evaluate(tabId => chrome.tabs.sendMessage(tabId, { type: 'ct:start', scope: 'all' }), tabId);
  await page.locator('nav [data-ct-owned="translation"]').waitFor();
  assert(await page.locator('aside [data-ct-owned]').count() === 0, '离屏侧栏仍按视口按需');
  await page.getByRole('button', { name: '显示原文', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).waitFor();
  let release;
  blocked = new Promise(resolve => { release = resolve; });
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).click();
  await page.getByRole('button', { name: '显示原文', exact: true }).click();
  release(); blocked = null;
  await page.waitForTimeout(300);
  assert(await page.locator('main [data-ct-owned]').count() === 0, '取消后迟到结果不能插入');
  fail = true;
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).click();
  await page.getByText('微软免费翻译请求过于频繁，请稍后重试或切换服务。', { exact: true }).waitFor();
  const failedCalls = calls.length;
  await page.locator('#dynamic').evaluate(el => { const p = document.createElement('p'); p.textContent = 'Do not keep requesting after quota errors.'; el.append(p); });
  await page.waitForTimeout(350);
  assert(calls.length === failedCalls, '限流后暂停页面，动态内容不继续冲击接口');
  fail = false;
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await page.locator('#first [data-ct-owned="translation"]').waitFor();
  await page.screenshot({ path: 'output/playwright/page-bilingual-0.6.0.png' });
  await page.getByRole('button', { name: '显示原文', exact: true }).click();
  await worker.evaluate(async () => { const stored = await chrome.storage.local.get('translation-settings-v1'); stored['translation-settings-v1'].page = { target: 'ja', selection: false, floating: false }; stored['translation-settings-v1'].providers.deepseek = { key: 'secret-browser-fixture', model: 'deepseek-flash' }; await chrome.storage.local.set(stored); });
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).waitFor({ state: 'hidden' });
  const popup = await context.newPage();
  const extensionURL = await worker.evaluate(() => chrome.runtime.getURL('popup.html'));
  await popup.goto(extensionURL);
  const safe = await popup.evaluate(() => chrome.runtime.sendMessage({ type: 'ct:settings-get' }));
  assert(!JSON.stringify(safe).includes('secret-browser-fixture'), '后台返回安全设置，Key不进入网页');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 850 });
    await worker.evaluate(tabId => chrome.tabs.sendMessage(tabId, { type: 'ct:selection-open', text: 'A complete selected sentence is translated into Chinese.' }), tabId);
    await panel.getByText('中文译文：A complete selected sentence is translated into Chinese.', { exact: true }).waitFor();
    const bounds = await panel.boundingBox();
    assert(bounds.x >= 0 && bounds.x + bounds.width <= width, `${width}px划词浮层溢出`);
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({ width: 1440, height: 980 });
  await worker.evaluate(tabId => chrome.tabs.update(tabId, { active: true }), tabId);
  await popup.reload();
  await popup.getByRole('button', { name: '翻译当前网页', exact: true }).waitFor();
  assert(await popup.getByRole('combobox', { name: '网页目标语言' }).inputValue() === 'ja', '工具栏恢复目标语言');
  await popup.getByRole('combobox', { name: '网页目标语言' }).selectOption('zh');
  await popup.getByRole('switch', { name: '网页右侧按钮' }).check();
  await page.getByRole('button', { name: '翻译当前网页', exact: true }).waitFor();
  await popup.getByRole('button', { name: '翻译当前网页', exact: true }).click();
  await page.locator('#first [data-ct-owned="translation"]').waitFor();
  await popup.getByRole('button', { name: '显示原文', exact: true }).click();
  assert(await page.locator('main [data-ct-owned]').count() === 0, '工具栏切换原文');
  await popup.getByRole('button', { name: '翻译整个页面（含导航和侧栏）' }).click();
  await page.locator('nav [data-ct-owned="translation"]').waitFor();
  await popup.getByRole('button', { name: '显示原文', exact: true }).click();
  await popup.screenshot({ path: 'output/playwright/page-popup-0.6.0.png' });
  await popup.close();
  return { status: 'passed', requests: calls.length, responseMode: 'controlled-fixtures', checks: ['主动启用前无文本请求', '原文下方双语', '代码块表单隐私排除', '技术段落内联标识符完整', '导航侧栏智能过滤', '目标语言去重', '视口按需加载', '动态段落与修改', '关闭精确恢复源DOM', '当前页内存缓存', '原链接事件', '划词按钮再发送', '算法多义词与例句喇叭', '原生复制', 'Escape关闭', '整页模式', '取消隔离迟到结果', '限流暂停与主动重试', '安全设置不含Key', '开关广播', '390px320px浮层', '工具栏服务语言偏好和双语原文切换', '工具栏整页范围'] };
}
